import AppKit

/// A full copy of a pasteboard's contents: every item, every type. Lets the
/// injector borrow the clipboard for a paste and put back exactly what the
/// user had, including images, rich text and file references.
public struct ClipboardSnapshot {

    /// Marks our own clipboard entry so clipboard managers (Maccy, Raycast,
    /// Paste, …) don't log every dictation. See nspasteboard.org.
    public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private let items: [[(NSPasteboard.PasteboardType, Data)]]

    public var isEmpty: Bool { items.isEmpty }

    public init(of pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }.filter { !$0.isEmpty }
    }

    /// Put `text` on the pasteboard, marked as transient. Returns the
    /// pasteboard's change count afterwards, for `restore(to:ifUnchangedSince:)`.
    @discardableResult
    public static func placeTransient(_ text: String, on pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// Restore the snapshot, unless something else has written to the
    /// pasteboard since `changeCount` (the user copied something new; keep it).
    /// Returns whether it restored.
    @discardableResult
    public func restore(to pasteboard: NSPasteboard, ifUnchangedSince changeCount: Int) -> Bool {
        guard pasteboard.changeCount == changeCount else { return false }
        pasteboard.clearContents()
        guard !items.isEmpty else { return true }
        let restored = items.map { pairs -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in pairs { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(restored)
        return true
    }
}
